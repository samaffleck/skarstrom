#!/usr/bin/env python3
"""Generate python/src/skarstrom/examples.py from the example decks.

Every deck in examples/decks/ becomes a module attribute, so editors complete
``skarstrom.examples.<name>`` and show the deck's title and description on
hover. The deck's file name (without .json) is the attribute name, so it must
be a Python identifier (CI fails otherwise; rename the deck).

    python scripts/gen_examples_module.py          # write the module
    python scripts/gen_examples_module.py --check  # fail if it is out of date

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DECKS = ROOT / "examples" / "decks"
OUT = ROOT / "python" / "src" / "skarstrom" / "examples.py"

HEADER = '''\
# GENERATED by scripts/gen_examples_module.py from examples/decks/ - do not edit.
"""The example decks shipped with skarstrom, one attribute per deck.

    import skarstrom

    sim = skarstrom.examples.Perez2019_A.load()           # or:
    sim = skarstrom.Simulation(skarstrom.examples.Perez2019_A)

    skarstrom.examples.Perez2019_A.title                  # the deck's title
    skarstrom.examples.Perez2019_A.copy_to("my_deck.json")  # edit your own copy
    [e.name for e in skarstrom.examples.ALL]              # every example
    skarstrom.examples.get("Perez2019_A")                 # by name (str)

Each attribute is a :class:`skarstrom.Example`. The decks reproduce published
PSA/VSA/TSA studies; see https://samaffleck.github.io/skarstrom/examples/.
"""

from typing import Tuple

from ._example import Example

'''

FOOTER = '''
ALL: Tuple[Example, ...] = (
@ALL_ITEMS@
)
"""Every example deck, in name order."""

_BY_NAME = {e.name: e for e in ALL}


def names() -> list:
    """Names of every example deck (sorted)."""
    return [e.name for e in ALL]


def get(name: str) -> Example:
    """An example by name; the ``.json`` suffix is optional. ``KeyError`` if there is none."""
    key = name[:-5] if name.endswith(".json") else name
    try:
        return _BY_NAME[key]
    except KeyError:
        import difflib

        close = difflib.get_close_matches(key, _BY_NAME, n=3)
        hint = f"; did you mean {', '.join(close)}?" if close else f"; available: {', '.join(_BY_NAME)}"
        raise KeyError(f"no example {name!r}{hint}") from None
'''


def deck_info(path: Path) -> tuple:
    deck = json.loads(path.read_text(encoding="utf-8"))
    root = deck.get("value0", deck)
    info = root.get("System_Information", {}) if isinstance(root, dict) else {}
    return str(info.get("Title", "") or ""), str(info.get("Description", "") or "")


def render() -> str:
    names = sorted(p.stem for p in DECKS.glob("*.json"))
    bad = [n for n in names if not n.isidentifier() or keyword.iskeyword(n) or n.startswith("_")]
    if bad:
        sys.exit(f"example deck names must be Python identifiers (rename the file): {', '.join(bad)}")
    exported = ["ALL", "Example", "get", "names", *names]
    out = [HEADER, "__all__ = [\n" + "".join(f'    "{n}",\n' for n in exported) + "]\n\n"]
    for n in names:
        title, desc = deck_info(DECKS / f"{n}.json")
        out.append(f"{n} = Example({n!r}, {title!r}, {desc!r})\n")
        doc = title or n
        if desc:
            doc += "\n\n" + desc
        doc = doc.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        wrapped = "\n".join(
            textwrap.fill(par, width=88, break_long_words=False, break_on_hyphens=False) if par else ""
            for par in doc.split("\n")
        )
        out.append(f'"""{wrapped}"""\n\n')
    out.append(FOOTER.replace("@ALL_ITEMS@", "\n".join(f"    {n}," for n in names)))
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the module is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_examples_module.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
