#!/usr/bin/env python3
"""Generate docs/validation.md from the paper-validation metrics.

    python scripts/docs/gen_validation_page.py                 # render from the committed summary
    python scripts/docs/gen_validation_page.py --merge DIR     # merge DIR/*.json into the summary first
    python scripts/docs/gen_validation_page.py --check         # fail if docs/validation.md is stale

1. With --merge, reads every <paper>__<case>.json written by
   adsim/test/fixtures/validation_metrics.h (ctest points the paper tests at
   <build>/validation) and rewrites adsim/test/papers/validation_summary.json.
2. Renders docs/validation.md (GENERATED - never edit it by hand) from the
   summary and adsim/test/papers/papers.json.

Standard library only.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _fmt import fmt, is_fraction_metric  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SUMMARY = ROOT / "adsim/test/papers/validation_summary.json"
MANIFEST = ROOT / "adsim/test/papers/papers.json"
PAGE = ROOT / "docs/validation.md"
REPO_URL = "https://github.com/samaffleck/skarstrom"

# What a metric is compared against: a measurement, the paper's own model, or
# an equilibrium fit. Defaults per paper, overridden by the quantity label.
DEFAULT_BASIS = {
    "arora_hasan_2021": "paper model",
    "casas_2012": "paper model",
    "ferre_2026": "paper model",
    "nguyen_2022": "experiment",
    "nguyen_2023": "experiment",
    "perez_2019": "experiment",
    "streb_2021": "experiment",
    "vysyarajua_2024": "experiment",
    "ward_2022": "experiment",
    "ward_pini_2024": "paper model",
}

METRIC_LABEL = {
    "abs_error": "abs. error",
    "rel_error": "rel. error",
    "rmse": "RMSE",
    "nrmse": "NRMSE",
    "max_rel_error": "max rel. error",
}


def merge_case_files(directory: Path) -> dict:
    if not directory.is_dir():
        sys.exit(f"metrics directory not found: {directory}")
    files = sorted(p for p in directory.iterdir() if p.suffix == ".json")
    if not files:
        sys.exit(f"no metric files in {directory}: run the paper tests first")
    cases = [json.loads(p.read_text(encoding="utf-8")) for p in files]
    cases.sort(key=lambda c: c["paper"] + c["case"])
    return {
        "generated": "GENERATED by scripts/docs/gen_validation_page.py from the paper tests — do not edit",
        "generated_at": _dt.date.today().isoformat(),
        "cases": cases,
    }


def basis_of(paper: str, c: dict, m: dict) -> str:
    q = m["quantity"].lower()
    if "vs paper model" in q:
        return "paper model"
    if "vs experiment" in q or "repeat experiment" in q:
        return "experiment"
    if c["case"] == "Isotherm_Table3":
        return "isotherm fit"
    if paper == "ward_2022" and m["tolerance"] is None:
        return "paper model (95% CI)"
    if paper == "casas_2012" and "experiment" in q:
        return "experiment"
    if paper == "streb_2021" and m["tolerance"] is None:
        return "experiment (text, approx.)"
    if paper == "vysyarajua_2024" and c["case"] == "DCB_HighPressure_N2":
        return "isotherm (derived)"
    return DEFAULT_BASIS.get(paper, "reference")


def _unit_suffix(m: dict) -> str:
    u = m.get("error_units")
    if u == "%":
        return " pp"
    if u and u != "-":
        return f" {u}"
    return ""


def fmt_error(m: dict) -> str:
    if m["error"] is None:
        return "—"
    if is_fraction_metric(m):
        return f"{fmt(100 * m['error'])} %"
    return f"{fmt(m['error'])}{_unit_suffix(m)}"


def fmt_tol(m: dict) -> str:
    if m["tolerance"] is None:
        return "info"
    if is_fraction_metric(m):
        return f"{fmt(100 * m['tolerance'])} %"
    return f"{fmt(m['tolerance'])}{_unit_suffix(m)}"


def cell(s) -> str:
    """Markdown-table-safe cell text."""
    s = "" if s is None else str(s)
    return (s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")
             .replace("$", "&#36;").replace("\n", " "))


def sim_ref_cells(m: dict):
    if m["metric"] in ("rmse", "nrmse"):
        return "curve", "digitised data"
    if m["metric"] == "max_rel_error":
        return "—", "—"
    u = f" {m['units']}" if m.get("units") and m["units"] != "-" else ""
    return f"{fmt(m['simulated'], 4)}{u}", f"{fmt(m['reference'], 4)}{u}"


def anchor(paper_id: str) -> str:
    return paper_id.replace("_", "-")


def render(summary: dict, manifest: list) -> str:
    by_paper: dict = {}
    for c in summary["cases"]:
        by_paper.setdefault(c["paper"], []).append(c)
    all_metrics = [(c, m) for c in summary["cases"] for m in c["metrics"]]
    asserted = [(c, m) for c, m in all_metrics if m["tolerance"] is not None]
    failing = [(c, m) for c, m in asserted if not m["pass"]]

    L: list = []
    out = L.append
    out("<!-- GENERATED — do not edit. Built by scripts/docs/gen_validation_page.py from")
    out("     adsim/test/papers/validation_summary.json, which the paper tests in adsim/test/papers/ write.")
    out("     Regenerate: run the paper tests (ctest), then")
    out("     python scripts/docs/gen_validation_page.py --merge <build>/validation -->")
    out("")
    out("# Validation")
    out("")
    out(f"Skarstrom is checked against published adsorption studies by automated tests. Every comparison on this page is produced by a test in [`adsim/test/papers/`]({REPO_URL}/tree/main/adsim/test/papers) that runs the bundled input deck, computes an explicit error metric against numbers transcribed from the paper (`reference_values.csv` in each paper folder) or digitised from its figures (`adsim/data/`), and writes the result to a machine-readable summary. This page is generated from that summary — it is never edited by hand.")
    out("")
    out("**How to read the tables.**")
    out("")
    out("- **Against** says what the reference is: an *experiment* (measured data — this is validation), the *paper model* (the authors' own simulation — a code-to-code comparison), or an isotherm fit.")
    out("- **NRMSE** is the root-mean-square difference between the simulated and the digitised outlet mole fraction, divided by the feed mole fraction of that component. **RMSE** on temperature is in kelvin. Purity and recovery errors are absolute, in percentage points (pp); productivity and breakthrough-time errors are relative.")
    out("- **Tolerance** is a regression bound set from the measured error of the current model, rounded up — not an acceptance criterion chosen in advance. A case \"passes\" when it reproduces its recorded error; a large tolerance means a large, documented disagreement, not a good fit. Rows marked *info* are recorded but not asserted (e.g. approximate values read from the paper text).")
    out("- Every input deck is a *prediction* with the paper's published parameters: adsim does not refit transport coefficients or feed velocities per experiment, and it does not model the sampling lines between column and detector. Known causes of disagreement are listed per paper below and in each folder's README.")
    out("")
    out("## Summary")
    out("")
    out(f"{len(summary['cases'])} cases from {len(by_paper)} publications; {len(asserted)} asserted comparisons ({len(failing)} outside their recorded tolerance) and {len(all_metrics) - len(asserted)} informational ones. Summary generated on {summary['generated_at']}.")
    out("")
    out("| Publication | Cases | Against | Comparisons | Median error | Worst error |")
    out("|---|---|---|---|---|---|")
    for p in manifest:
        cases = by_paper.get(p["id"])
        if not cases:
            continue
        ms = [(c, m) for c in cases for m in c["metrics"] if m["tolerance"] is not None]
        bases = ", ".join(dict.fromkeys(basis_of(p["id"], c, m) for c, m in ms))
        families: dict = {}
        for _, m in ms:
            fam = f"abs:{m.get('error_units')}" if m["metric"] == "abs_error" else m["metric"]
            families.setdefault(fam, []).append(m)

        def stat(pick):
            parts = []
            for arr in families.values():
                srt = sorted(arr, key=lambda m: m["error"])
                m = pick(srt)
                parts.append(f"{fmt_error(m)} ({METRIC_LABEL.get(m['metric'], m['metric'])})")
            return "<br/>".join(parts)

        median = lambda a: a[(len(a) - 1) // 2]  # noqa: E731
        worst = lambda a: a[-1]  # noqa: E731
        out(f"| [{cell(p['label'])}](#{anchor(p['id'])}) | {len(cases)} | {cell(bases)} | {len(ms)} | {stat(median)} | {stat(worst)} |")
    out("")

    for p in manifest:
        cases = by_paper.get(p["id"])
        out(f"## {cell(p['label'])} {{#{anchor(p['id'])}}}")
        out("")
        sec = f"; [doi:{p['doi_secondary']}](https://doi.org/{p['doi_secondary']})" if p.get("doi_secondary") else ""
        out(f"{cell(p['citation'])} [doi:{p['doi']}](https://doi.org/{p['doi']}){sec}")
        out("")
        out(f"*System:* {cell(p['system'])}. *Compared against:* {cell(p['reference_kind'])}.")
        out("")
        if p.get("findings"):
            out("**Findings.**")
            out("")
            for f in p["findings"]:
                out(f"- {cell(f)}")
            out("")
        if not cases:
            out("_No metrics recorded in this summary._")
            out("")
            continue
        out("| Case | Quantity | Against | Simulated | Reference | Error | Tolerance | Source |")
        out("|---|---|---|---|---|---|---|---|")
        for c in cases:
            for m in c["metrics"]:
                sim, ref = sim_ref_cells(m)
                flag = " **(outside)**" if m["tolerance"] is not None and not m["pass"] else ""
                out(f"| {cell(c['case'])} | {cell(m['quantity'])} | {cell(basis_of(p['id'], c, m))} | {cell(sim)} | {cell(ref)} | "
                    f"{cell(fmt_error(m))} {cell(METRIC_LABEL.get(m['metric'], m['metric']))}{flag} | {cell(fmt_tol(m))} | {cell(m.get('source'))} |")
        out("")
        notes = list(dict.fromkeys(m.get("note") for c in cases for m in c["metrics"] if m.get("note")))
        if notes:
            out('??? note "Notes on these comparisons"')
            out("")
            for n in notes:
                out(f"    - {cell(n)}")
            out("")
        out(f"Input decks, assumptions and known discrepancies: [`adsim/test/papers/{p['id']}/README.md`]({REPO_URL}/blob/main/adsim/test/papers/{p['id']}/README.md).")
        out("")

    out("## Reproducing this page")
    out("")
    out("```bash")
    out("cmake --preset linux-release")
    out("cmake --build --preset linux-release")
    out('ctest --preset linux-release -R "(Arora2021|Casas2012|Ferre2026|Nguyen2022|Nguyen2023|Perez2019|Streb2021|Vysyaraju2024|Ward2022|WardPini2024)" -j2')
    out("python scripts/docs/gen_validation_page.py --merge build/linux-release/validation")
    out("```")
    out("")
    out("Each test writes `<build>/validation/<paper>__<case>.json`; the script merges them into `adsim/test/papers/validation_summary.json` and regenerates this page. The test suite also writes about 4 GB of results to `adsim/Results/`; delete it afterwards.")
    out("")
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--merge", metavar="DIR", type=Path, help="merge per-case metric files from DIR into the summary first")
    ap.add_argument("--check", action="store_true", help="fail if docs/validation.md is out of date")
    args = ap.parse_args(argv)
    if args.merge and args.check:
        ap.error("--merge and --check are exclusive")
    if args.merge:
        summary = merge_case_files(args.merge)
        SUMMARY.write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {SUMMARY.relative_to(ROOT)} ({len(summary['cases'])} cases)")
    else:
        summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))["papers"]
    text = render(summary, manifest)
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else None
        if current != text:
            print(f"DRIFT: {PAGE.relative_to(ROOT)} is out of date - run python scripts/docs/gen_validation_page.py",
                  file=sys.stderr)
            return 1
        print(f"{PAGE.relative_to(ROOT)} is up to date ({len(summary['cases'])} cases)")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
