"""Record Cantera's molecular diffusivities for the engine's components:

    core/test/unit/cantera_diffusion_reference.h

test_cantera_diffusivity.cpp compares the engine with these values. The engine
does not build or call Cantera.

Each component is a Cantera species with the engine's Lennard-Jones pair
(Components::componentData, eps/k and sigma) and no dipole, so that Cantera
also uses the nonpolar Lorentz-Berthelot combining rule. The comparison then
tests the engine's Chapman-Enskog and Neufeld implementation and its
mixture-averaged rule, not the choice of Lennard-Jones parameters. Cantera's
molar masses come from its atomic weights (within 1.5e-4 of the engine's,
which moves D_ij by less than 1e-4).

  binary    GasTransportData + mixture-averaged transport, binary_diff_coeffs,
            for every pair (self pairs included) at P = 1 bar.
  mixture   mix_diff_coeffs_mole (Blanc's law: (1 - x_k) / sum_j x_j / D_kj)
            for a few mixtures away from the pure limit, at 300 K and 1 bar.

Needs Cantera (pip install cantera); the version is recorded in the header.

Usage:
    python scripts/gen_cantera_diffusion_reference.py           # write the header
    python scripts/gen_cantera_diffusion_reference.py --check   # fail if the committed header differs
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_transport_coefficients import component_names, lennard_jones  # noqa: E402

import cantera as ct  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "core/test/unit/cantera_diffusion_reference.h"

PRESSURE = 1e5
TEMPERATURES = (200.0, 300.0, 650.0)

# Elemental composition of each component (Cantera computes the molar mass).
FORMULA = {
    "Ammonia": "N:1 H:3", "Argon": "Ar:1", "Benzene": "C:6 H:6", "Butane": "C:4 H:10",
    "CarbonDioxide": "C:1 O:2", "CarbonMonoxide": "C:1 O:1", "Cyclohexane": "C:6 H:12",
    "Ethane": "C:2 H:6", "Ethanol": "C:2 H:6 O:1", "Ethylene": "C:2 H:4", "Fluorine": "F:2",
    "Helium": "He:1", "Hydrogen": "H:2", "HydrogenSulfide": "H:2 S:1", "Isobutane": "C:4 H:10",
    "Isopentane": "C:5 H:12", "Krypton": "Kr:1", "Methane": "C:1 H:4", "Methanol": "C:1 H:4 O:1",
    "Neon": "Ne:1", "Nitrogen": "N:2", "NitrousOxide": "N:2 O:1", "Octane": "C:8 H:18",
    "Oxygen": "O:2", "Pentane": "C:5 H:12", "Propane": "C:3 H:8", "Propylene": "C:3 H:6",
    "SulfurDioxide": "S:1 O:2", "SulfurHexafluoride": "S:1 F:6", "Toluene": "C:7 H:8",
    "Water": "H:2 O:1", "Xenon": "Xe:1",
}

# (title, components, mole fractions), all at 300 K and 1 bar.
MIXTURES = [
    ("SMR off-gas", ["Hydrogen", "CarbonDioxide", "Methane", "CarbonMonoxide"], [0.75, 0.17, 0.05, 0.03]),
    ("Air", ["Nitrogen", "Oxygen", "Argon"], [0.78, 0.21, 0.01]),
    ("Flue gas", ["Nitrogen", "CarbonDioxide", "Water"], [0.75, 0.15, 0.10]),
    ("Equimolar H2/CO2/N2", ["Hydrogen", "CarbonDioxide", "Nitrogen"], [1 / 3, 1 / 3, 1 / 3]),
    ("Trace CO2 in H2/N2", ["Hydrogen", "Nitrogen", "CarbonDioxide"], [0.4995, 0.4995, 0.001]),
]


def solution(names: list[str], lj: dict[str, tuple[float, float]]) -> ct.Solution:
    species = []
    for n in names:
        eps, sigma = lj[n]
        s = ct.Species(n, FORMULA[n])
        # The thermo does not enter the binary diffusivity; it sets the
        # temperature range of Cantera's transport fits (100-1000 K).
        s.thermo = ct.ConstantCp(100, 1000, ct.one_atm, (298.15, 0, 0, 30e3))
        tr = ct.GasTransportData()
        # Geometry enters only the viscosity and conductivity, not D_ij.
        tr.set_customary_units("nonlinear", sigma, eps, 0.0, 0.0, 0.0)
        s.transport = tr
        species.append(s)
    return ct.Solution(thermo="ideal-gas", transport_model="mixture-averaged", species=species)


def header() -> str:
    names = component_names()
    lj = lennard_jones()
    missing = [n for n in names if n not in FORMULA]
    if missing:
        sys.exit(f"add the composition of {missing} to FORMULA")
    gas = solution(names, lj)

    tables = []
    for T in TEMPERATURES:
        gas.TPX = T, PRESSURE, {names[0]: 1.0}
        tables.append(gas.binary_diff_coeffs.copy())

    out = []
    out.append("""/*
 * Skarstrom - pressure and temperature swing adsorption simulator
 * Copyright (c) 2024-2026 Sam Affleck and contributors
 *
 * Licensed under the terms in the LICENSE file at the repository root.
 */
// GENERATED by scripts/gen_cantera_diffusion_reference.py. Do not edit.
//
// Molecular diffusivities [m^2/s] recorded from Cantera with the engine's
// Lennard-Jones pairs and no dipole (refer to the script). The engine does not
// build or call Cantera; test_cantera_diffusivity.cpp compares with these.
#pragma once

#include <array>
#include <string>
#include <vector>

namespace adsim::cantera_reference {
""")
    out.append(f'  inline const std::string kCanteraVersion = "{ct.__version__}";')
    out.append(f"  inline constexpr double kPressure = {PRESSURE:.1f};  // [Pa]")
    out.append("  inline constexpr std::array<double, 3> kTemperatures = { "
               + ", ".join(f"{T:.1f}" for T in TEMPERATURES) + " };  // [K]\n")
    out.append("  // The Lennard-Jones inputs (eps/k [K], sigma [Angstrom]) the values were recorded with.")
    out.append("  struct LennardJonesInput { std::string name; double eps; double sigma; };")
    out.append("  inline const std::vector<LennardJonesInput> kInputs = {")
    for n in names:
        out.append(f'    {{ "{n}", {lj[n][0]!r}, {lj[n][1]!r} }},')
    out.append("  };\n")
    out.append("  // binary_diff_coeffs at kTemperatures and kPressure; self pairs included.")
    out.append("  struct BinaryReference { std::string a, b; std::array<double, 3> D; };")
    out.append("  inline const std::vector<BinaryReference> kBinary = {")
    for i, a in enumerate(names):
        for j in range(i, len(names)):
            b = names[j]
            vals = ", ".join(f"{tab[i, j]:.9e}" for tab in tables)
            out.append(f'    {{ "{a}", "{b}", {{ {vals} }} }},')
    out.append("  };\n")
    out.append("  // mix_diff_coeffs_mole at 300 K and kPressure.")
    out.append("  struct MixtureReference {")
    out.append("    std::string title;")
    out.append("    std::vector<std::string> components;")
    out.append("    std::vector<double> y, D;")
    out.append("  };")
    out.append("  inline const std::vector<MixtureReference> kMixtures = {")
    for title, comps, ys in MIXTURES:
        gas.TPX = 300.0, PRESSURE, dict(zip(comps, ys))
        d = gas.mix_diff_coeffs_mole
        out.append(f'    {{ "{title}",')
        out.append("      { " + ", ".join(f'"{c}"' for c in comps) + " },")
        out.append("      { " + ", ".join(f"{y!r}" for y in ys) + " },")
        out.append("      { " + ", ".join(f"{d[gas.species_index(c)]:.9e}" for c in comps) + " } },")
    out.append("  };\n")
    out.append("} // namespace adsim::cantera_reference\n")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed header differs")
    args = ap.parse_args()
    text = header()
    if args.check:
        old = OUT.read_text(encoding="utf-8")
        if old != text:
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), text.splitlines(True), str(OUT.relative_to(ROOT)), "generated", n=1))
            print(f"\n{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_cantera_diffusion_reference.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
