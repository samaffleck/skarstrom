#!/usr/bin/env python3
"""Generate examples/_build/: every example deck as a builder script.

Each script builds its deck from scratch with the skarstrom builder API
(``skarstrom.to_script``), every structural choice and value explicit, so it
is a starting point for a deck of your own written in code.
python/tests/test_build.py checks that each script reproduces its deck.

    python scripts/gen_build_seeds.py                   # write all scripts
    python scripts/gen_build_seeds.py Perez2019_A ...   # only these decks

Needs the skarstrom package (pip install . in a checkout).
"""

from __future__ import annotations

import sys
from pathlib import Path

import skarstrom

ROOT = Path(__file__).resolve().parents[1]
DECKS = ROOT / "examples" / "decks"
OUT = ROOT / "examples" / "_build"

HEADER = '''\
# GENERATED by scripts/gen_build_seeds.py from examples/decks/{name}.json - regenerate, do not edit.
"""{title}: the deck built from scratch with the skarstrom builder API.

Every structural choice and value of examples/decks/{name}.json, in code
(python/tests/test_build.py checks that this script reproduces the deck).
Copy it to start a deck of your own.

    python examples/_build/{name}.py [cycles]   # build, then run
"""

'''

FOOTER = '''

if __name__ == "__main__":
    import sys

    result = sim.run(cycles=int(sys.argv[1]) if len(sys.argv) > 1 else None)
    print(result.status, f"after {{result.cycles_run}} cycles")
    for k in sim.kpis(cycle=-1):
        print(f"{{k.component}}: purity {{k.purity:.4f}}, recovery {{k.recovery:.4f}}")
'''


def main(names: list) -> int:
    OUT.mkdir(exist_ok=True)
    for path in sorted(DECKS.glob("*.json")):
        name = path.stem
        if names and name not in names:
            continue
        sim = skarstrom.Simulation.from_file(path)
        title = sim.get_text("info.title").replace('"""', "'''") or name
        body = skarstrom.to_script(sim)
        (OUT / f"{name}.py").write_text(HEADER.format(name=name, title=title) + body + FOOTER.format())
        print("wrote", (OUT / f"{name}.py").relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
