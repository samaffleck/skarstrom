"""The resolved adsorbent library (data/adsorbents/library.resolved.json) is in
sync with the catalogue, follows its schema and agrees with the engine.

The file is generated by scripts/docs/gen_adsorbent_library.py: regenerate it
there, never by hand.
"""
import importlib.util
import json
from pathlib import Path

import pytest

import skarstrom as sk

ROOT = Path(__file__).resolve().parents[2]
LIB_DIR = ROOT / "data" / "adsorbents"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("gen_adsorbent_library", ROOT / "scripts" / "docs" / "gen_adsorbent_library.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def committed():
    return json.loads((LIB_DIR / "library.resolved.json").read_text(encoding="utf-8"))


def test_regeneration_gives_the_committed_file(gen):
    entries, errors = gen.load_library()
    assert errors == []
    engine = gen.load_engine()
    assert engine is not None
    text = gen.render_resolved(entries, engine)
    assert (LIB_DIR / "library.resolved.json").read_text(encoding="utf-8") == text, (
        "library.resolved.json is out of date: run python scripts/docs/gen_adsorbent_library.py")
    assert gen.check_resolved_schema(text) == []


def test_committed_file_follows_the_json_schema(committed):
    jsonschema = pytest.importorskip("jsonschema")
    schema = json.loads((LIB_DIR / "library.resolved.schema.json").read_text(encoding="utf-8"))
    jsonschema.Draft202012Validator.check_schema(schema)
    jsonschema.Draft202012Validator(schema).validate(committed)


def test_entries_match_the_merged_catalogue(committed):
    merged = json.loads((LIB_DIR / "library.merged.json").read_text(encoding="utf-8"))
    assert [e["key"] for e in committed["entries"]] == [e["key"] for e in merged["entries"]]
    for r, m in zip(committed["entries"], merged["entries"]):
        assert r["recommended"] == m["recommended"]
        assert r["components"] == m["components"]


def test_isotherms_use_the_engine_tables(committed):
    kinds = {k["tag"]: k for k in sk.model_kinds()["isotherm"]}
    for e in committed["entries"]:
        for iso in e["isotherms"]:
            d = kinds[iso["kind"]]
            assert iso["kind_label"] == d["label"]
            assert [p["name"] for p in iso["parameters"]] == [p["name"] for p in d["parameters"]]
            assert [p["unit"] for p in iso["parameters"]] == [p["unit"] for p in d["parameters"]]


def test_script_tables_agree_with_the_engine(gen):
    kinds = sk.model_kinds()["isotherm"]
    assert gen.ISOTHERM_KINDS == [k["tag"] for k in kinds]
    assert [gen.ISOTHERM_LABELS[t] for t in gen.ISOTHERM_KINDS] == [k["label"] for k in kinds]


def test_source_points_are_in_si(committed):
    seen = 0
    for e in committed["entries"]:
        for iso in e["isotherms"]:
            sp = iso["source_points"]
            if not sp:
                continue
            seen += 1
            n = sp["summary"]["n"]
            assert len(sp["T_K"]) == len(sp["p_Pa"]) == len(sp["q_mol_per_kg"]) == n
            assert min(sp["T_K"]) > 0 and min(sp["p_Pa"]) >= 0
            assert sp["summary"]["T_range_K"] == [min(sp["T_K"]), max(sp["T_K"])]
    assert seen > 0


def test_completeness_and_provenance(committed):
    incomplete = [e for e in committed["entries"] if not e["completeness"]["complete"]]
    assert incomplete, "the catalogue has known gaps; a gap must be reported, not hidden"
    for e in committed["entries"]:
        assert bool(e["completeness"]["missing"]) == (not e["completeness"]["complete"])
        for p in e["properties"]:
            assert p["provenance"] and p["provenance_label"]
        assert [m["component"] for m in e["mass_transfer"]] == e["components"]
